#!/usr/bin/env bash
# Run with: sudo ~/matching-engine/deploy/regen-fixs-gateway.sh
# Regenerates the :5443 plain-FIX gateway allowlist from fix_allow.json
# and reloads nginx. Run after editing the allowlist in the admin console.
set -euo pipefail
ALLOW_FILE="${FIXS_ALLOW_FILE:-/opt/velexa-sim-me/fix_allow.json}"
OUT=/etc/nginx/stream-enabled/fixs-gateway.conf

RULES=$(python3 - "$ALLOW_FILE" <<'PY'
import json,sys,ipaddress
try:
    d = json.load(open(sys.argv[1]))
except Exception:
    d = {}
ips = [k.strip() for k in d.keys() if k.strip()]
# always permit loopback + this host so the admin health check works
base = ["127.0.0.1", "10.238.41.107"]
out = []
for ip in base + ips:
    try:
        ipaddress.ip_network(ip, strict=False)
    except ValueError:
        continue
    if ip not in [o[1] for o in out]:
        label = d.get(ip, "") if ip in d else "local"
        out.append((label, ip))
if not ips:
    # empty allowlist = open to all, per admin console semantics
    print("        # fix_allow.json empty -> open to all")
    print("        allow all;")
else:
    for label, ip in out:
        c = f"  # {label}" if label else ""
        print(f"        allow {ip};{c}")
    print("        deny all;")
PY
)

tee "$OUT" >/dev/null <<EOF
# Velexa ME — external plain-FIX gateway :5443 -> 127.0.0.1:5001
# Generated by regen-fixs-gateway.sh from $ALLOW_FILE
# Network gate only; every session still authenticates with SenderCompID + FIX tag 554.
server {
    listen 5443;
    listen [::]:5443;

$RULES

    proxy_pass 127.0.0.1:5001;
    proxy_timeout 24h;
    proxy_connect_timeout 5s;

    access_log /var/log/nginx/fixs-gateway.access.log basic;
    error_log  /var/log/nginx/fixs-gateway.error.log;
}
EOF
nginx -t && systemctl reload nginx && echo "FIXS gateway reloaded:" && grep -E 'allow|deny' "$OUT"
