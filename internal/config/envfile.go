package config

// The engine takes its settings from environment variables. So that `go run .`
// or `./bin/velexa-sim-me` picks up a local env file without exporting it first,
// the file is loaded when the program starts — before any other package reads
// a setting, because every package that reads one imports config.
//
// File: ME_ENV_FILE if set, otherwise ./me.env, otherwise (on a server)
// /opt/velexa-sim-me/me.env. A variable that is already set in the environment
// is left alone: the environment wins over the file. When there is no file at
// all (a fresh clone on a new PC), one is written from me.env.example with a
// random admin password and session secret, so the engine starts ready to use.

import (
	"bufio"
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"fmt"
	"log"
	"os"
	"strings"
	"testing"
	"time"
)

func init() { loadEnvFile() }

// EnvFile is the env file that was loaded at start-up ("" when none).
var EnvFile string

func envFilePath() string {
	if p := strings.TrimSpace(os.Getenv("ME_ENV_FILE")); p != "" {
		if fileExists(p) {
			return p
		}
		return "" // not there (yet): generated on first run unless ME_ENV_GENERATE=off
	}
	if _, err := os.Stat("me.env"); err == nil {
		return "me.env"
	}
	if OnServer() {
		if p := serverStateDir + "/me.env"; fileExists(p) {
			return p
		}
	}
	return ""
}

// newEnvFilePath is where a first-run env file is written.
func newEnvFilePath() string {
	if p := strings.TrimSpace(os.Getenv("ME_ENV_FILE")); p != "" {
		return p
	}
	if OnServer() {
		return serverStateDir + "/me.env"
	}
	return "me.env"
}

// writeFirstRunEnv writes the env template to path (never over an existing
// file) with a random admin password and session secret, mode 0600.
func writeFirstRunEnv(path string) error {
	user := EnvOr("ME_ADMIN_USER", "admin")
	body := strings.Replace(envTemplate, "\nME_ADMIN_PASS=\n", "\nME_ADMIN_PASS="+randomAdminPass(user)+"\n", 1)
	body = strings.Replace(body, "\nME_ADMIN_SECRET=\n", "\nME_ADMIN_SECRET="+randomHex(32)+"\n", 1)
	body = fmt.Sprintf("# Generated by the matching engine on its first run, %s.\n", time.Now().Format("2006-01-02 15:04")) + body
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if err != nil {
		log.Printf("[config] no env file, and could not create %s: %v", path, err)
		return err
	}
	defer f.Close()
	if _, err := f.WriteString(body); err != nil {
		return err
	}
	log.Printf("[config] first run: created %s with a random admin password and session secret — sign in as %q with ME_ADMIN_PASS from that file", path, user)
	return nil
}

// randomAdminPass makes a password that meets the console's rules: long, mixed
// classes, and not containing the username.
func randomAdminPass(user string) string {
	for {
		b := make([]byte, 15)
		if _, err := rand.Read(b); err != nil {
			panic("config: no randomness: " + err.Error())
		}
		p := "Me-" + base64.RawURLEncoding.EncodeToString(b) + "-7q"
		if user == "" || !strings.Contains(strings.ToLower(p), strings.ToLower(user)) {
			return p
		}
	}
}

func randomHex(n int) string {
	b := make([]byte, n)
	if _, err := rand.Read(b); err != nil {
		panic("config: no randomness: " + err.Error())
	}
	return hex.EncodeToString(b)
}

func fileExists(p string) bool {
	_, err := os.Stat(p)
	return err == nil
}

func loadEnvFile() {
	path := envFilePath()
	if path == "" {
		if testing.Testing() || strings.EqualFold(os.Getenv("ME_ENV_GENERATE"), "off") {
			return
		}
		if path = newEnvFilePath(); writeFirstRunEnv(path) != nil {
			return
		}
	}
	vars, err := ReadEnvFile(path)
	if err != nil {
		log.Printf("[config] could not read %s: %v", path, err)
		return
	}
	set, kept := 0, 0
	for _, kv := range vars {
		if _, exists := os.LookupEnv(kv[0]); exists {
			kept++
			continue
		}
		os.Setenv(kv[0], kv[1])
		set++
	}
	EnvFile = path
	log.Printf("[config] loaded %d settings from %s (%d already set in the environment were kept)", set, path, kept)
}

// ReadEnvFile parses a KEY=VALUE file: blank lines and lines starting with #
// are skipped, an "export " prefix is allowed, a value may be wrapped in single
// or double quotes, and an unquoted value ends at " #" (a trailing comment).
// Values are not expanded.
func ReadEnvFile(path string) ([][2]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out [][2]string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(strings.TrimPrefix(sc.Text(), "\ufeff"))
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		line = strings.TrimSpace(strings.TrimPrefix(line, "export "))
		key, val, ok := strings.Cut(line, "=")
		key = strings.TrimSpace(key)
		if !ok || key == "" || strings.ContainsAny(key, " \t") {
			continue
		}
		val = strings.TrimSpace(val)
		if n := len(val); n >= 2 && (val[0] == '"' || val[0] == '\'') && val[n-1] == val[0] {
			val = val[1 : n-1]
		} else if i := strings.Index(val, " #"); i >= 0 {
			val = strings.TrimSpace(val[:i])
		}
		out = append(out, [2]string{key, val})
	}
	return out, sc.Err()
}
